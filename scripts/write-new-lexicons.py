def pack(rows, lines):
    if len(rows) != 64 or len(lines) != 12:
        raise SystemExit(f"bad size {len(rows)} {len(lines)} first={rows[0][0] if rows else '?'}")
    entries = {}
    for key, row in zip(KEYS, rows):
        word, reading, sentence = row
        item = {"word": word, "sentence": sentence}
        if reading:
            item["reading"] = reading
        entries[key] = item
    return {"entries": entries, "lines": dict(zip(LINES, lines))}


