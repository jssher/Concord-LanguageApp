def item(glyph, name, sound, word, gloss, reading=""):
    row = {"glyph": glyph, "name": name, "sound": sound, "word": word, "gloss": gloss}
    if reading:
        row["reading"] = reading
    return row


def group(gid, name, items):
    return {"id": gid, "name": name, "items": items}


