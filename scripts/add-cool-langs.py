"""Core decks and alphabets for the extra languages."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EN = json.loads((ROOT / "src/data/lexicon/en.json").read_text())
KEYS = list(EN["entries"])
LINES = list(EN["lines"])


def pack(entries, lines):
    missing = [k for k in KEYS if k not in entries]
    extra = [k for k in entries if k not in KEYS]
    bad_lines = [k for k in LINES if k not in lines]
    if missing or extra or bad_lines:
        raise SystemExit(f"keys missing={missing} extra={extra} lines={bad_lines}")
    for key, row in entries.items():
        if not row.get("word") or not row.get("sentence"):
            raise SystemExit(f"empty {key}")
    return {"entries": entries, "lines": lines}


def e(word, sentence, **rest):
    row = {"word": word, "sentence": sentence}
    row.update(rest)
    return row


