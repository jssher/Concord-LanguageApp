export type Side = "n" | "e" | "s" | "w" | "c";

export type Spot = {
  en: string;
  x?: number;
  y?: number;
  side?: Side;
  /** How many columns this square uses on a grid plate. */
  span?: number;
};

export type PicturePlate = {
  id: string;
  title: string;
  section: string;
  kind: "scene" | "grid";
  image: string;
  blurb: string;
  pad?: number;
  /** Number only, sitting on the thing. The word is on the card. */
  compact?: boolean;
  spots: Spot[];
};

function scene(id: string, title: string, section: string, blurb: string, spots: Spot[], compact = false): PicturePlate {
  return { id, title, section, kind: "scene", image: `/pictures/${id}.jpg`, blurb, spots, compact };
}

function grid(id: string, title: string, section: string, blurb: string, pad: number, words: (string | Spot)[]): PicturePlate {
  return {
    id,
    title,
    section,
    kind: "grid",
    image: `/pictures/${id}.jpg`,
    blurb,
    pad,
    spots: words.map((item) => (typeof item === "string" ? { en: item } : item)),
  };
}

